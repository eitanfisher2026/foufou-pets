import { doc, getDoc, setDoc } from 'firebase/firestore';
import { db } from '../../firebase.js';

const DOC_PATH = ['config', 'helpContent'];

const DEFAULT_TEXT = `🐾 איתור חיות מחמד עוזרת לכם לחפש חתול או כלב אבוד, ומתאימה אוטומטית בין דיווחים על חיות שאבדו לדיווחים על חיות שנראו או נמצאו.

😿 חיה שלכם אבדה?
• לוחצים על הכפתור האדום "החיה שלי אבדה" במסך הבית
• ממלאים מה שידוע: צבע, סימנים מיוחדים, המקום האחרון שראיתם אותה
• ככל שיהיה יותר פירוט - כך קל יותר למצוא התאמה מדויקת

🐾 ראיתם או מצאתם חיה?
• לוחצים על הכפתור הירוק "ראיתי / מצאתי"
• אין צורך להכיר את הבעלים - רק מדווחים על מה שראיתם, איפה ומתי
• אם החיה אצלכם עכשיו, מציינים את זה בטופס

📲 הכי מהיר: שיתוף ישירות מפייסבוק (Meta)
ראיתם פוסט על חיה אבודה או שנמצאה בפייסבוק / Meta? אין צורך להעתיק שום דבר ביד:
1. לוחצים על "שיתוף" בפוסט בפייסבוק (Meta)
2. בוחרים באפליקציה "איתור חיות מחמד" מרשימת האפשרויות לשיתוף
3. האפליקציה קוראת את הפוסט לבד וממלאת את רוב הפרטים אוטומטית - נשאר רק לבדוק ולאשר

✨ לא בטוחים מה זה? "הוספה חכמה"
• לא יודעים אם זו אבידה או מציאה, או אם זה חתול או כלב?
• כפתור "הוספה חכמה" בעמוד הראשי מזהה הכל לבד - מהתמונה או מהפוסט

🔍 בדיקת התאמות
• בכל תיק חיפוש יש כפתור "בדיקת התאמות"
• האפליקציה משווה מול כל הדיווחים שנמצאו, ומציגה התאמות אפשריות לפי רמת סבירות
• כל התאמה מוצגת עם הסבר פשוט - למה היא נראית מתאימה

💡 טיפים
• כמה שיותר תמונות וסימנים מיוחדים = יותר סיכוי למציאה
• מצאתם את החיה? עדכנו את הסטטוס בתיק כדי שלא ימשיכו לחפש אותה
• יש הערה, רעיון, או משהו לא עובד? אפשר לשלוח משוב ישירות דרך תפריט הפרופיל (התמונה למעלה)`;

/**
 * Admin-editable help text, stored at config/helpContent - same live-
 * editable convention as aboutContentApi.js. Hebrew only.
 */
export async function getHelpContent() {
  const snap = await getDoc(doc(db, ...DOC_PATH));
  return snap.exists() && snap.data().text ? snap.data().text : DEFAULT_TEXT;
}

export async function saveHelpContent(text) {
  await setDoc(doc(db, ...DOC_PATH), { text }, { merge: true });
}
